-- Esquema de CampusFest para H2.
-- Lo ejecuta RepositorioEventosH2 al crearse. IF NOT EXISTS permite ejecutarlo varias veces.

CREATE TABLE IF NOT EXISTS EVENTO (
    ID          VARCHAR(64)  NOT NULL,
    NOMBRE      VARCHAR(200) NOT NULL,
    FECHA       TIMESTAMP    NOT NULL,
    LUGAR       VARCHAR(200) NOT NULL,
    AFORO       INT          NOT NULL,
    BLOQUEADOS  INT          NOT NULL,
    CONSTRAINT PK_EVENTO PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS RESERVA (
    CODIGO         VARCHAR(64) NOT NULL,
    EVENTO_ID      VARCHAR(64) NOT NULL,
    ESTUDIANTE_ID  VARCHAR(64) NOT NULL,
    VENCE_EN       TIMESTAMP   NOT NULL,
    ESTADO         VARCHAR(20) NOT NULL,
    CONSTRAINT PK_RESERVA PRIMARY KEY (CODIGO),
    CONSTRAINT FK_RESERVA_EVENTO FOREIGN KEY (EVENTO_ID) REFERENCES EVENTO (ID)
);

CREATE TABLE IF NOT EXISTS ASISTENCIA (
    RESERVA_CODIGO  VARCHAR(64) NOT NULL,
    HORA            TIMESTAMP   NOT NULL,
    CONSTRAINT PK_ASISTENCIA PRIMARY KEY (RESERVA_CODIGO),
    CONSTRAINT FK_ASISTENCIA_RESERVA FOREIGN KEY (RESERVA_CODIGO) REFERENCES RESERVA (CODIGO)
);
